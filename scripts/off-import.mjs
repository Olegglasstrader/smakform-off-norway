#!/usr/bin/env node
// Step 1 of the Open Food Facts import: stream the full CSV export (~1.5 GB gz) and keep only the
// products sold in Norway, with the columns the diary needs. Nothing big is stored: the dump is
// gunzipped on the fly and filtered line by line.
//
//   node scripts/off-import.mjs            # → work/off-no.jsonl
//
// Source: https://world.openfoodfacts.org/data (Open Food Facts). Licence: database ODbL 1.0,
// contents DbCL 1.0, images CC BY-SA (images are NOT used). Legal 06.11
// bulk = the dump, never the live API; the
// OFF rows stay in their own table/file, never merged with Matvaretabellen or our own data in one
// record (ODbL 4.4 derivative database), attribution in the app.

import { createWriteStream, mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PassThrough, Readable } from 'node:stream';
import { finished, pipeline } from 'node:stream/promises';
import { createGunzip } from 'node:zlib';
import { createInterface } from 'node:readline';

// Raw Norway rows go to ./work (not published: the full OFF rows, regenerated by this script).
const OUT_DIR = fileURLToPath(new URL('../work/', import.meta.url));
const OUT = join(OUT_DIR, 'off-no.jsonl');
const URL = 'https://static.openfoodfacts.org/data/en.openfoodfacts.org.products.csv.gz';
const UA = 'Smakform/0.1 (+https://smakform.no)';

const KEEP = [
  'code', 'product_name', 'generic_name', 'quantity', 'brands', 'categories_tags', 'countries_tags', 'stores',
  'ingredients_text', 'allergens', 'traces_tags', 'serving_quantity', 'no_nutrition_data', 'last_modified_t', 'unique_scans_n',
  'energy-kj_100g', 'energy-kcal_100g', 'fat_100g', 'saturated-fat_100g', 'carbohydrates_100g', 'sugars_100g',
  'fiber_100g', 'proteins_100g', 'salt_100g',
  // Only for the energy plausibility check (nutrition-expert 06.11), not shown in the app.
  'polyols_100g', 'alcohol_100g',
];

const res = await fetch(URL, { headers: { 'user-agent': UA }, redirect: 'follow' });
if (!res.ok || !res.body) throw new Error(`HTTP ${res.status}`);
mkdirSync(OUT_DIR, { recursive: true });
// Dump date = the file's Last-Modified (stored as the data version on diary rows).
const dumpDate = new Date(res.headers.get('last-modified') ?? Date.now()).toISOString().slice(0, 10);
const TMP = OUT + '.tmp';
const out = createWriteStream(TMP);
// pipeline() forwards a network / gunzip error, so a broken download fails instead of ending quietly.
const text = new PassThrough();
const piping = pipeline(Readable.fromWeb(res.body), createGunzip(), text);
const rl = createInterface({ input: text, crlfDelay: Infinity });

let idx = null;
let total = 0;
let kept = 0;
for await (const line of rl) {
  if (!idx) {
    const head = line.split('\t');
    idx = Object.fromEntries(KEEP.map((k) => [k, head.indexOf(k)]));
    const missing = KEEP.filter((k) => idx[k] < 0);
    if (missing.length) throw new Error(`columns missing: ${missing.join(', ')}`);
    continue;
  }
  total++;
  if (total % 500_000 === 0) console.log(`… ${total} rows, ${kept} Norwegian`);
  if (!line.includes('en:norway')) continue;
  const f = line.split('\t');
  if (!(f[idx.countries_tags] ?? '').split(',').includes('en:norway')) continue;
  const row = {};
  for (const k of KEEP) row[k] = f[idx[k]] ?? '';
  out.write(JSON.stringify(row) + '\n');
  kept++;
}
await piping;
out.end();
await finished(out);
// A cut-off dump must never replace a good file.
if (total < 1_000_000) throw new Error(`only ${total} rows read — dump incomplete, ${OUT} not replaced`);
if (kept < 15_000) console.warn(`⚠ only ${kept} Norwegian products`);
renameSync(TMP, OUT);
writeFileSync(join(OUT_DIR, 'off-no.meta.json'), JSON.stringify({ dumpDate, total, kept }) + '\n');
console.log(`✓ ${kept} Norwegian products of ${total} → ${OUT}`);
